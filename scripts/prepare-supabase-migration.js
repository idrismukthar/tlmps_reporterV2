require("dotenv").config();
const fs = require("fs");
const path = require("path");
const sqlite3 = require("sqlite3").verbose();

function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i];
    if (!token.startsWith("--")) continue;
    const key = token.slice(2);
    const next = argv[i + 1];
    if (next && !next.startsWith("--")) {
      args[key] = next;
      i += 1;
    } else {
      args[key] = true;
    }
  }
  return args;
}

function resolveOutputPath(inputPath) {
  if (!inputPath) {
    return path.resolve(__dirname, "../backups/tlmps-supabase-migration.sql");
  }
  return path.isAbsolute(inputPath)
    ? inputPath
    : path.resolve(process.cwd(), inputPath);
}

function escapeSqlValue(value, column, onEmptyNumeric) {
  if (
    value === "" &&
    /^(INTEGER|REAL|NUMERIC|BOOLEAN)$/i.test(column.type || "")
  ) {
    if (column.notnull) {
      throw new Error(
        `Cannot map an empty string in required numeric column "${column.name}" to PostgreSQL.`,
      );
    }
    onEmptyNumeric();
    return "NULL";
  }
  if (value === null || typeof value === "undefined") return "NULL";
  if (typeof value === "number") {
    if (!Number.isFinite(value)) return "NULL";
    return String(value);
  }
  if (typeof value === "boolean") return value ? "TRUE" : "FALSE";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function normalizeSchemaSql(sql) {
  if (!sql) return "";

  let normalized = sql.trim();
  normalized = normalized.replace(
    /INTEGER\s+PRIMARY KEY(?:\s+AUTOINCREMENT)?/gi,
    "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
  );
  normalized = normalized.replace(/AUTOINCREMENT/gi, "");
  normalized = normalized.replace(/CREATE TABLE\s+(["`]?)([A-Za-z0-9_]+)\1\s*\(/i, "CREATE TABLE IF NOT EXISTS \"$2\" (");

  return normalized.replace(/\s+/g, " ").trim();
}

async function openDatabase(dbPath) {
  return new Promise((resolve, reject) => {
    const db = new sqlite3.Database(dbPath, sqlite3.OPEN_READONLY, (openError) => {
      if (openError) {
        reject(openError);
        return;
      }
      resolve(db);
    });
  });
}

async function fetchTables(db) {
  return new Promise((resolve, reject) => {
    db.all(
      "SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name",
      [],
      (error, rows) => {
        if (error) {
          reject(error);
          return;
        }
        resolve(rows || []);
      },
    );
  });
}

async function fetchRows(db, tableName) {
  return new Promise((resolve, reject) => {
    db.all(`SELECT * FROM "${tableName}"`, [], (error, rows) => {
      if (error) {
        reject(error);
        return;
      }
      resolve(rows || []);
    });
  });
}

async function fetchIntegerPrimaryKeys(db, tableName) {
  return new Promise((resolve, reject) => {
    db.all(`PRAGMA table_info("${tableName}")`, [], (error, rows) => {
      if (error) {
        reject(error);
        return;
      }
      resolve(
        (rows || [])
          .filter((row) => row.pk > 0 && /^INTEGER$/i.test(row.type || ""))
          .map((row) => row.name),
      );
    });
  });
}

async function fetchTableColumns(db, tableName) {
  return new Promise((resolve, reject) => {
    db.all(`PRAGMA table_info("${tableName}")`, [], (error, rows) => {
      if (error) {
        reject(error);
        return;
      }
      resolve(rows || []);
    });
  });
}

async function orderTablesByDependencies(db, tables) {
  const names = new Set(tables.map((table) => table.name));
  const dependencies = new Map();

  for (const table of tables) {
    const references = await new Promise((resolve, reject) => {
      db.all(`PRAGMA foreign_key_list("${table.name}")`, [], (error, rows) => {
        if (error) {
          reject(error);
          return;
        }
        resolve((rows || []).map((row) => row.table).filter((name) => name !== table.name && names.has(name)));
      });
    });
    dependencies.set(table.name, new Set(references));
  }

  const ordered = [];
  const remaining = new Set(names);
  while (remaining.size) {
    const ready = [...remaining]
      .filter((name) => [...dependencies.get(name)].every((dependency) => !remaining.has(dependency)))
      .sort();
    if (!ready.length) {
      throw new Error("The SQLite schema contains cyclic foreign-key dependencies; refusing to generate an unsafe import.");
    }
    for (const name of ready) {
      ordered.push(tables.find((table) => table.name === name));
      remaining.delete(name);
    }
  }
  return ordered;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const dbPath =
    args.db ||
    process.env.DB_PATH ||
    path.resolve(__dirname, "../tlmps.db");
  const outputPath = resolveOutputPath(args.output || process.env.MIGRATION_OUTPUT_PATH);

  const resolvedDbPath = path.resolve(dbPath);
  const db = await openDatabase(resolvedDbPath);

  try {
    const tables = await orderTablesByDependencies(db, await fetchTables(db));
    if (!tables.length) {
      throw new Error(`No user tables were found in ${resolvedDbPath}`);
    }

    const outputLines = [
      "-- SQLite to Supabase migration export",
      `-- Source database: ${resolvedDbPath}`,
      `-- Exported: ${new Date().toISOString()}`,
      "",
      "BEGIN;",
      "",
    ];

    let totalRows = 0;
    let emptyNumericStrings = 0;

    for (const table of tables) {
      const schemaSql = normalizeSchemaSql(table.sql);
      const tableName = table.name;
      if (!schemaSql) {
        continue;
      }

      outputLines.push(`-- Table: ${tableName}`);
      outputLines.push(schemaSql + ";");
      outputLines.push("");

      const rows = await fetchRows(db, tableName);
      const columnInfo = new Map(
        (await fetchTableColumns(db, tableName)).map((column) => [column.name, column]),
      );
      totalRows += rows.length;

      if (!rows.length) {
        continue;
      }

      const columns = Object.keys(rows[0]);
      outputLines.push(
        `INSERT INTO "${tableName}" (${columns.map((column) => `"${column}"`).join(", ")}) VALUES`,
      );

      rows.forEach((row, index) => {
        const values = columns.map((column) =>
          escapeSqlValue(row[column], columnInfo.get(column), () => {
            emptyNumericStrings += 1;
          }),
        );
        const suffix = index === rows.length - 1 ? ";" : ",";
        outputLines.push(`  (${values.join(", ")})${suffix}`);
      });

      outputLines.push("");
    }

    if (emptyNumericStrings) {
      outputLines.push(
        `-- Converted ${emptyNumericStrings} empty-string values in nullable numeric columns to NULL.`,
        "",
      );
    }

    for (const table of tables) {
      for (const column of await fetchIntegerPrimaryKeys(db, table.name)) {
        outputLines.push(
          `SELECT setval(pg_get_serial_sequence('"${table.name}"', '${column}'), COALESCE(MAX("${column}"), 1), MAX("${column}") IS NOT NULL) FROM "${table.name}";`,
        );
      }
      outputLines.push(`ALTER TABLE public."${table.name}" ENABLE ROW LEVEL SECURITY;`);
      outputLines.push(`REVOKE ALL ON TABLE public."${table.name}" FROM PUBLIC, anon, authenticated;`);
      outputLines.push("");
    }

    outputLines.push("COMMIT;");

    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, `${outputLines.join("\n")}\n`, "utf8");

    console.log(`Prepared Supabase migration export for ${tables.length} tables and ${totalRows} rows.`);
    if (emptyNumericStrings) {
      console.log(
        `Mapped ${emptyNumericStrings} empty strings in nullable numeric fields to NULL for PostgreSQL compatibility.`,
      );
    }
    console.log(`Output: ${outputPath}`);
  } finally {
    db.close();
  }
}

main().catch((error) => {
  console.error("Failed to prepare Supabase migration export.");
  console.error(error.message || error);
  process.exitCode = 1;
});
